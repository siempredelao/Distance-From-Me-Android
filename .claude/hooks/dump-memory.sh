#!/usr/bin/env bash
# Regenerates MEMORY.md at the repo root as a verbatim copy of Claude Code's
# project memory (~/.claude/projects/<project>/memory/).
#
# Called from Claude Code hooks:
#   - PostToolUse on Write|Edit: stdin carries the tool input; only acts when
#     the written file is inside the memory directory.
#   - Stop: no relevant stdin; always regenerates, to catch memory changes made
#     without Write/Edit (for example a deleted note).
# MEMORY.md is only rewritten when its content would change.
set -euo pipefail

project_dir="${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/../.." && pwd)}"
memory_dir="$HOME/.claude/projects/${project_dir//\//-}/memory"
dump="$project_dir/MEMORY.md"

# On PostToolUse, ignore writes outside the memory directory.
input="$(cat || true)"
file_path="$(printf '%s' "$input" | jq -r '.tool_input.file_path // empty' 2>/dev/null || true)"
if [[ -n "$file_path" && "$file_path" != "$memory_dir"/* ]]; then
  exit 0
fi

[[ -d "$memory_dir" ]] || exit 0

notes=()
while IFS= read -r -d '' note; do
  notes+=("$note")
done < <(find "$memory_dir" -maxdepth 1 -type f -name '*.md' ! -name 'MEMORY.md' -print0 | sort -z)

# Prints a file, adding a final newline if it lacks one, so the closing fence
# always starts its own line.
print_file() {
  cat "$1"
  [[ -z "$(tail -c 1 "$1")" ]] || printf '\n'
}

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
  printf '# Claude Code memory dump\n\n'
  printf 'Verbatim copy of `~/.claude/projects/%s/memory/`, regenerated by `.claude/hooks/dump-memory.sh` whenever the memory changes. Do not edit by hand.\n' "${project_dir//\//-}"
  if [[ -f "$memory_dir/MEMORY.md" ]]; then
    printf '\n## MEMORY.md (index)\n\n```markdown\n'
    print_file "$memory_dir/MEMORY.md"
    printf '```\n'
  fi
  for note in ${notes[@]+"${notes[@]}"}; do
    printf '\n## %s\n\n```markdown\n' "$(basename "$note")"
    print_file "$note"
    printf '```\n'
  done
} > "$tmp"

if ! cmp -s "$tmp" "$dump"; then
  chmod 644 "$tmp"
  mv "$tmp" "$dump"
  trap - EXIT
fi
